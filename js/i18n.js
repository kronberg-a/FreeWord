// Current UI Language (stored in localStorage)
let currentLang = 'en';

export function initI18n() {
  const saved = localStorage.getItem('freeword_ui_lang');
  if (saved && SUPPORTED_LANGUAGES[saved]) {
    currentLang = saved;
  } else {
    const navLang = (navigator.language || 'en').slice(0, 2).toLowerCase();
    currentLang = SUPPORTED_LANGUAGES[navLang] ? navLang : 'en';
  }
  return currentLang;
}

export function getCurrentLanguage() {
  return currentLang;
}

export function setLanguage(langCode) {
  if (SUPPORTED_LANGUAGES[langCode]) {
    currentLang = langCode;
    localStorage.setItem('freeword_ui_lang', langCode);
    notifyLanguageChanged();
    return true;
  }
  return false;
}

export function t(key, params = {}) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  let str = dict[key] || TRANSLATIONS.en[key] || key;
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(param => {
      str = str.replace(new RegExp(`\\{${param}\\}`, 'g'), params[param]);
    });
  }
  return str;
}

const listeners = [];
export function onLanguageChange(fn) {
  if (typeof fn === 'function') listeners.push(fn);
}

function notifyLanguageChanged() {
  listeners.forEach(fn => {
    try { fn(currentLang); } catch (e) { console.error('i18n callback error:', e); }
  });
}
